/** Six questions per chapter, reusing the six established ground pickup anchors. */
export function getChapterFruitSpots(chapter: number) {
  return companionSnackSpots.flatMap((anchor, index) =>
    [1, 2, 3, 4, 5, 6].filter(act => act <= chapter).map(act => ({
      ...anchor, id: `${chapterSpirit[act]}:${anchor.id}`, spiritId: chapterSpirit[act],
      questionIndex: index, act,
    })),
  );
}

/** Normalize bare legacy anchors and WorldScene's indexed aliases to the anchor IDs above.
 * Call per species when loading claims; unknown IDs survive for forward compatibility.
 */
export function migrateChapterFruitIds(spirit: AvailableSpirit, claimedIds: readonly string[]): string[] {
  return [...new Set(claimedIds.map(id => {
    const index = companionSnackSpots.findIndex((anchor, index) =>
      id === anchor.id || id === `${spirit}:fruit-${index}`);
    return index < 0 ? id : `${spirit}:${companionSnackSpots[index].id}`;
  }))];
}
