/** Progress is an exact ordered prefix, so malformed/restored claims cannot skip records. */
export function completeLateActStep(chapter: LateActNumber, completed: string[], id: string): string[] {
  const steps = lateActs[chapter].steps;
  if (completed.some((value, index) => steps[index]?.id !== value) || steps[completed.length]?.id !== id) {
    return completed;
  }
  return [...completed, id];
}

export function lateActComplete(chapter: LateActNumber, completed: readonly string[]): boolean {
  const steps = lateActs[chapter].steps;
  return completed.length === steps.length && steps.every((step, index) => completed[index] === step.id);
}
